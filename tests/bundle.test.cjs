'use strict';
// The committed paste file (and the generated .gs copies) match what npm run bundle writes.
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { outputs } = require('../scripts/build-apps-script.cjs');

const root = path.join(__dirname, '..');
const lf = s => s.replace(/\r\n/g, '\n');

test('the paste file and the generated .gs files are up to date', () => {
  for (const [rel, expected] of Object.entries(outputs())) {
    const p = path.join(root, rel);
    assert.ok(fs.existsSync(p), rel + ' is missing: run npm run bundle');
    assert.equal(lf(fs.readFileSync(p, 'utf8')), expected, rel + ' is out of date: run npm run bundle and commit it');
  }
});

test('the paste file starts with @OnlyCurrentDoc and says it is generated', () => {
  const text = fs.readFileSync(path.join(root, 'paste-into-apps-script', 'SeatedMeals.gs'), 'utf8');
  assert.ok(text.startsWith('/** @OnlyCurrentDoc */\n// Generated by npm run bundle'));
  assert.ok(fs.readFileSync(path.join(root, 'apps-script', 'Main.gs'), 'utf8').startsWith('/** @OnlyCurrentDoc */'));
});
