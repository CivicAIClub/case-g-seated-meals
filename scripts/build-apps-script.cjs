'use strict';
// npm run bundle: copies each core/ file into apps-script/ as a generated .gs file, then joins them
// with Main.gs into paste-into-apps-script/SeatedMeals.gs, the one file a person pastes into the
// Apps Script editor. Run it after every change to core/ or apps-script/Main.gs.
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const MODULES = [['read.js', 'Read.gs'], ['history.js', 'History.gs'], ['seat.js', 'Seat.gs'], ['output.js', 'Output.gs'], ['practice.js', 'Practice.gs']];
const PASTE_FILE = path.join(root, 'paste-into-apps-script', 'SeatedMeals.gs');
const lf = s => s.replace(/\r\n/g, '\n');

// What the build writes, without writing it: { 'apps-script/Read.gs': text, ..., paste file: text }.
function outputs() {
  const files = {};
  for (const [source, target] of MODULES) {
    files['apps-script/' + target] = '// Generated from core/' + source + ' by npm run bundle. Edit core/' + source + ', then rebuild.\n' + lf(fs.readFileSync(path.join(root, 'core', source), 'utf8'));
  }
  const main = lf(fs.readFileSync(path.join(root, 'apps-script', 'Main.gs'), 'utf8'));
  const parts = MODULES.map(([, target]) => files['apps-script/' + target]).concat(main).map(s => s.trimEnd());
  files['paste-into-apps-script/SeatedMeals.gs'] = '/** @OnlyCurrentDoc */\n// Generated by npm run bundle from core/ and apps-script/Main.gs. Do not edit this file; edit those and rebuild.\n' +
    '// Paste all of it into Code.gs in the spreadsheet\'s Apps Script editor (Extensions > Apps Script).\n\n' + parts.join('\n\n') + '\n';
  return files;
}

function build() {
  const files = outputs();
  fs.mkdirSync(path.dirname(PASTE_FILE), { recursive: true });
  for (const [rel, text] of Object.entries(files)) fs.writeFileSync(path.join(root, rel), text);
  return files;
}

if (require.main === module) {
  build();
  console.log('Built paste-into-apps-script/SeatedMeals.gs. Paste all of it into Code.gs in the spreadsheet\'s Apps Script editor.');
}
module.exports = { build, outputs, MODULES };
